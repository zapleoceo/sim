#!/usr/bin/python3
"""CI gate: the migrations build exactly the schema of sim/db/models.py.

Runs only against the disposable CI PostgreSQL (SIM_PG_DISPOSABLE=YES, SIM_PG_TEST_URL on
localhost, never with SIM_ENV=prod). It creates a scratch database next to the test database,
so the pytest schema is not touched, and then:

1. `alembic upgrade heads` on the empty database (SIM branch + Procrastinate branch);
2. Procrastinate's tables exist;
3. every enum CHECK constraint allows exactly the values of its enum;
4. `alembic check` (autogenerate comparison, Procrastinate tables ignored) finds no difference
   between the migrated database and the models;
5. `alembic downgrade sim@base` removes every SIM table and sequence;
6. upgrading again works and the comparison is still clean.

Usage (CI, from backend/): uv run python scripts/ci_postgres_smoke.py"""
from __future__ import annotations

import asyncio
import os
import re
import sys
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Enum, MetaData, text
from sqlalchemy.engine import URL, make_url
from sqlalchemy.ext.asyncio import create_async_engine

from sim.db.models import Base

BACKEND = Path(__file__).resolve().parents[1]
LOCAL_HOSTS = frozenset({"127.0.0.1", "localhost", "::1"})
SCRATCH_SUFFIX = "_migrations"
PROCRASTINATE_TABLES = frozenset({"procrastinate_jobs", "procrastinate_events",
                                  "procrastinate_periodic_defers", "procrastinate_workers"})
QUOTED = re.compile(r"'((?:[^']|'')*)'")


class GateError(Exception):
    """The migrated schema does not match the models."""


def require_disposable(env: dict[str, str]) -> URL:
    """The CI test database URL, or SystemExit when this is not a disposable local database."""
    raw = env.get("SIM_PG_TEST_URL", "")
    url = make_url(raw) if raw else None
    if (env.get("SIM_PG_DISPOSABLE") != "YES" or url is None
            or env.get("SIM_ENV", "").lower() == "prod"
            or url.get_backend_name() != "postgresql" or url.host not in LOCAL_HOSTS
            or not url.database):
        raise SystemExit("needs a disposable local PostgreSQL: SIM_PG_DISPOSABLE=YES and "
                         "SIM_PG_TEST_URL=postgresql+psycopg://...@127.0.0.1/<db>")
    return url


def scratch_url(url: URL) -> URL:
    return url.set(database=f"{url.database}{SCRATCH_SUFFIX}")


def check_values(definition: str) -> set[str]:
    """Allowed values of a CHECK constraint as PostgreSQL prints it
    (`CHECK (((kind)::text = ANY ((ARRAY['a'::character varying, ...])::text[])))`)."""
    return {value.replace("''", "'") for value in QUOTED.findall(definition)}


def expected_checks(metadata: MetaData) -> dict[tuple[str, str], set[str]]:
    """(table, constraint name) -> allowed values, for every enum column of the models."""
    expected: dict[tuple[str, str], set[str]] = {}
    for table in metadata.sorted_tables:
        for column in table.columns:
            if isinstance(column.type, Enum):
                name = f"ck_{table.name}_{column.type.name}"
                expected[(table.name, name)] = set(column.type.enums)
    return expected


def compare_checks(expected: dict[tuple[str, str], set[str]],
                   actual: dict[tuple[str, str], set[str]]) -> list[str]:
    problems = []
    for key, values in sorted(expected.items()):
        if key not in actual:
            problems.append(f"missing CHECK {key[1]} on {key[0]}")
        elif actual[key] != values:
            problems.append(f"CHECK {key[1]} on {key[0]} allows {sorted(actual[key])}, "
                            f"the enum has {sorted(values)}")
    return problems


async def recreate_database(admin_url: URL, name: str, *, create: bool = True) -> None:
    engine = create_async_engine(admin_url, isolation_level="AUTOCOMMIT")
    try:
        async with engine.connect() as conn:
            await conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
            if create:
                await conn.execute(text(f'CREATE DATABASE "{name}"'))
    finally:
        await engine.dispose()


async def database_checks(url: URL) -> dict[tuple[str, str], set[str]]:
    engine = create_async_engine(url)
    try:
        async with engine.connect() as conn:
            rows = (await conn.execute(text(
                "SELECT rel.relname, con.conname, pg_get_constraintdef(con.oid) "
                "FROM pg_constraint con JOIN pg_class rel ON rel.oid = con.conrelid "
                "JOIN pg_namespace ns ON ns.oid = rel.relnamespace "
                "WHERE con.contype = 'c' AND ns.nspname = 'public'"))).all()
    finally:
        await engine.dispose()
    return {(table, name): check_values(definition) for table, name, definition in rows}


async def public_relations(url: URL) -> tuple[set[str], set[str]]:
    """(tables, sequences) in the public schema."""
    engine = create_async_engine(url)
    try:
        async with engine.connect() as conn:
            rows = (await conn.execute(text(
                "SELECT c.relname, c.relkind FROM pg_class c "
                "JOIN pg_namespace ns ON ns.oid = c.relnamespace "
                "WHERE ns.nspname = 'public' AND c.relkind IN ('r', 'S')"))).all()
    finally:
        await engine.dispose()
    tables = {name for name, kind in rows if kind == "r"}
    sequences = {name for name, kind in rows if kind == "S"}
    return tables, sequences


def alembic_config(url: URL) -> Config:
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.attributes["database_url"] = url.render_as_string(hide_password=False)
    return cfg


def assert_no_diffs(cfg: Config) -> None:
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:
        lines = "\n".join(f"  {diff}" for diff in exc.diffs)
        raise GateError(f"migrations differ from sim/db/models.py:\n{lines}") from None


def run_gate(url: URL) -> None:
    cfg = alembic_config(url)
    app_tables = set(Base.metadata.tables)

    print("1. alembic upgrade heads on an empty database")
    command.upgrade(cfg, "heads")

    tables, sequences = asyncio.run(public_relations(url))
    if missing := (app_tables | PROCRASTINATE_TABLES) - tables:
        raise GateError(f"tables missing after upgrade: {sorted(missing)}")
    if missing := {f"{name}_id_seq" for name in app_tables} - sequences:
        raise GateError(f"id sequences missing after upgrade: {sorted(missing)}")
    print(f"2. {len(app_tables)} SIM tables and the Procrastinate queue exist")

    if problems := compare_checks(expected_checks(Base.metadata),
                                  asyncio.run(database_checks(url))):
        raise GateError("enum CHECK constraints differ from sim/domain/enums.py:\n  "
                        + "\n  ".join(problems))
    print("3. enum CHECK constraints match the enums")

    assert_no_diffs(cfg)
    print("4. autogenerate finds no difference between migrations and models")

    command.downgrade(cfg, "sim@base")
    tables, sequences = asyncio.run(public_relations(url))
    if left := (tables & app_tables) | {s for s in sequences if not s.startswith("procrast")}:
        raise GateError(f"left after downgrade sim@base: {sorted(left)}")
    print("5. alembic downgrade sim@base removed every SIM table")

    command.upgrade(cfg, "heads")
    assert_no_diffs(cfg)
    print("6. upgrade after downgrade is clean")


def main() -> int:
    base = require_disposable(dict(os.environ))
    scratch = scratch_url(base)
    asyncio.run(recreate_database(base, scratch.database or ""))
    try:
        run_gate(scratch)
    except GateError as exc:
        print(f"::error::{exc}")
        return 1
    finally:
        asyncio.run(recreate_database(base, scratch.database or "", create=False))
    print("migration gate passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
