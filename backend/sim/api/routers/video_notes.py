"""AI video note of a persona for the one allowlisted owner account (sim.services.video_note)."""
from __future__ import annotations

from typing import Literal

from fastapi import APIRouter
from pydantic import Field, field_validator

from sim.api.deps import App, Db, Owner
from sim.api.schemas import Body
from sim.services.video_note import (
    MAX_DURATION_S,
    MAX_PROMPT_CHARS,
    MIN_DURATION_S,
    VideoNoteRequest,
)

router = APIRouter(prefix="/api/personas/{persona_id}/video-note", tags=["video-note"])


class VideoNoteIn(Body):
    prompt: str = Field(min_length=1, max_length=MAX_PROMPT_CHARS)
    duration_s: int = Field(5, ge=MIN_DURATION_S, le=MAX_DURATION_S)
    resolution: Literal["360p", "720p"] = "360p"
    reference_media_id: int | None = None

    @field_validator("prompt")
    @classmethod
    def nonblank(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Prompt must not be blank")
        return value


@router.post("", status_code=202)
async def request_video_note(persona_id: int, body: VideoNoteIn, c: App, s: Db, _: Owner):
    """Queue an AI video note. It goes ONLY to the account from the owner setting
    `video_note_owner_telegram_id`; while that is 0 the request is refused (VideoNoteRefused →
    409, sim.api.errors) and nothing is generated. The same request is served from the cache (`cached: true`), a new one is
    generated by the Broker. The worker sends "Сгенерировано ИИ" and then the note."""
    return await c.video_notes(s).request(VideoNoteRequest(
        persona_id, body.prompt, body.duration_s, body.resolution, body.reference_media_id,
    ))
