PLACEHOLDER = re.compile(r"\{([a-z_]+)\}")
_current: dict[str, str] = {}


def publish(values: Mapping[str, object]) -> None:
    """The owner's texts as just read from the settings; they replace the published ones whole."""
    global _current
    _current = {key: value for key, value in values.items() if key in DEFAULTS and isinstance(value, str)}


def text(key: str) -> str:
    """The text in force: the owner's published value, else the code default."""
    return _current.get(key) or DEFAULTS[key]


def fill(key: str, **values: object) -> str:
    """The text with its structural placeholders (`{name}`) filled in one pass: a value that
    itself contains braces is never substituted again; unknown placeholders stay as written,
    so JSON examples in a text need no escaping."""
    return PLACEHOLDER.sub(lambda m: str(values[m.group(1)]) if m.group(1) in values else m.group(0),
                           text(key))
